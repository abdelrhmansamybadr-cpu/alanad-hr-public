"""Feature fair_decisions: reasons are required, employees dispute, managers/HR answer on the record, reversal really reopens.
Run:  python api_test17_decisions.py http://127.0.0.1:8098
"""
import datetime
from feat_common import *

print("== setup")
hr, hr_uid, C = company("fair")
boss_tok, BOSS, _ = employee(hr, "boss", salary=15000)
emp_tok, EID, _ = employee(hr, "worker", salary=8000, manager_id=BOSS)
other_tok, OID, _ = employee(hr, "other", salary=8000)
today = datetime.date.today()
d1 = (today + datetime.timedelta(days=20)).isoformat(); d2 = (today + datetime.timedelta(days=21)).isoformat()


def new_leave(tok, a=d1, b=d2):
    s, r = call("POST", "/leaves", {"type": "annual", "start_date": a, "end_date": b, "reason": "family"}, tok)
    assert s == 201, (s, r)
    return r["id"]


print("== feature off: closed, and rejecting needs no reason as before")
s, r = call("GET", "/decisions", None, emp_tok)
check("decisions closed while off", s == 403 and r.get("code") == "feature_disabled", f"{s} {r}")
L0 = new_leave(emp_tok)
s, r = call("PUT", f"/leaves/{L0}", {"status": "rejected"}, hr)
check("rejection without a reason still allowed when the feature is off", s == 200, f"{s} {r}")

print("== switch on")
switch(C, fair_decisions=True)
L1 = new_leave(emp_tok, (today + datetime.timedelta(days=30)).isoformat(), (today + datetime.timedelta(days=31)).isoformat())
s, r = call("PUT", f"/leaves/{L1}", {"status": "rejected"}, boss_tok)
check("manager must give a reason to reject a leave", s == 422, f"{s} {r}")
s, r = call("PUT", f"/leaves/{L1}", {"status": "rejected", "review_note": "   "}, boss_tok)
check("blank reason refused", s == 422, f"{s}")
s, r = call("PUT", f"/leaves/{L1}", {"status": "rejected", "review_note": "Two people are already off that week"}, boss_tok)
check("rejection with a reason works", s == 200, f"{s} {r}")
s, r = call("POST", "/requests", {"type": "equipment", "title": "Parking spot", "description": "need one"}, emp_tok)
R1 = r.get("id")
check("request created", s == 201 and R1, f"{s} {r}")
s, r = call("PUT", f"/requests/{R1}", {"status": "rejected"}, hr)
check("request rejection also needs a reason", s == 422, f"{s} {r}")
s, r = call("PUT", f"/requests/{R1}", {"status": "rejected", "review_note": "No free spots this quarter"}, hr)
check("request rejected with a reason", s == 200, f"{s} {r}")
s, r = call("PUT", f"/leaves/{new_leave(emp_tok, (today + datetime.timedelta(days=40)).isoformat(), (today + datetime.timedelta(days=41)).isoformat())}", {"status": "approved"}, boss_tok)
check("approving needs no reason", s == 200, f"{s}")

print("== a lost point (manual, red) and a payslip with deductions appear as decisions")
s, r = call("POST", "/points/adjust", {"employee_id": EID, "color": "red", "note": "Left the shop unattended", "date": today.isoformat()}, hr)
check("HR gives a manual red point", s == 201, f"{s} {r}")
PT = [h for h in r["history"] if h["color"] == "red" and h["source"] == "manual"][0]["id"]

print("== who sees what")
s, r = call("GET", "/decisions", None, emp_tok)
kinds = sorted(x["kind"] for x in r)
check("employee sees own: 2 leaves, request, point", s == 200 and kinds.count("leave") == 2 and kinds.count("request") == 1 and kinds.count("point") == 1, f"{kinds}")
leave_item = [x for x in r if x["kind"] == "leave" and x["refId"] == L1][0]
old_item = [x for x in r if x["kind"] == "leave" and x["refId"] == L0][0]
check("a decision taken before the feature was on is flagged: no reason given", old_item["hasReason"] is False, f"{old_item}")
check("the reason is shown", leave_item["reasonText"].startswith("Two people") and leave_item["hasReason"] is True and leave_item["decidedBy"], f"{leave_item}")
s, r = call("GET", "/decisions", None, other_tok)
check("a colleague sees nothing of it", s == 200 and r == [], f"{r}")
s, r = call("GET", "/decisions", None, boss_tok)
check("manager sees the team's decisions", s == 200 and len(r) >= 4 and all(x["employeeId"] == EID for x in r), f"{len(r)}")
s, r = call("GET", "/decisions", None, hr)
check("HR sees everything", s == 200 and len(r) >= 3, f"{len(r)}")
s, r = call("GET", f"/decisions/leave/{L1}", None, other_tok)
check("colleague cannot open someone else's decision", s == 404, f"{s}")

print("== employee disputes")
s, r = call("POST", f"/decisions/leave/{L1}/dispute", {"message": "no"}, emp_tok)
check("too short a message refused", s == 422, f"{s}")
s, r = call("POST", f"/decisions/leave/{L1}/dispute", {"message": "I arranged cover with Omar for those days"}, other_tok)
check("only the affected person can dispute", s == 404 or s == 403, f"{s}")
s, r = call("POST", f"/decisions/leave/{L1}/dispute", {"message": "I arranged cover with Omar for those days"}, hr)
check("HR cannot dispute on behalf of someone", s == 403, f"{s}")
s, r = call("POST", f"/decisions/leave/{L1}/dispute", {"message": "I arranged cover with Omar for those days"}, emp_tok)
check("dispute recorded", s == 201 and r["dispute"]["status"] == "open", f"{s} {r}")
s, r = call("POST", f"/decisions/leave/{L1}/dispute", {"message": "I arranged cover with Omar again"}, emp_tok)
check("only one dispute per decision", s == 409, f"{s}")
s, r = call("GET", "/notifications", None, boss_tok)
rows = r.get("items", [])
check("manager is notified", any(n.get("type") == "decision" for n in rows), f"{rows[:2]}")

print("== answering")
s, r = call("PUT", f"/decisions/leave/{L1}/respond", {"status": "reversed", "response": "ok"}, emp_tok)
check("the employee cannot answer their own dispute", s == 403, f"{s}")
s, r = call("PUT", f"/decisions/leave/{L1}/respond", {"status": "reversed", "response": "ok"}, other_tok)
check("a colleague cannot answer", s in (403, 404), f"{s}")
s, r = call("PUT", f"/decisions/leave/{L1}/respond", {"status": "maybe", "response": "ok then"}, boss_tok)
check("invalid status refused", s == 422, f"{s}")
s, r = call("PUT", f"/decisions/leave/{L1}/respond", {"status": "reversed", "response": "Cover confirmed, approved"}, boss_tok)
check("manager reverses: dispute answered", s == 200 and r["dispute"]["status"] == "reversed", f"{s} {r}")
s, r = call("GET", f"/leaves/{L1}", None, emp_tok)
check("reversal reopened the leave (pending)", r.get("status") == "pending", f"{r.get('status')}")
s, r = call("PUT", f"/decisions/leave/{L1}/respond", {"status": "upheld", "response": "changed my mind"}, boss_tok)
check("a dispute can only be answered once (the reopened leave is no longer an adverse decision)", s in (404, 409), f"{s}")
s, r = call("GET", "/notifications", None, emp_tok)
rows = r.get("items", [])
check("employee is notified of the answer", any(n.get("type") == "decision" for n in rows), f"{rows[:2]}")

print("== points and requests")
s, r = call("POST", f"/decisions/point/{PT}/dispute", {"message": "The shop was locked and Sara was inside"}, emp_tok)
check("point disputed", s == 201, f"{s} {r}")
s, r = call("PUT", f"/decisions/point/{PT}/respond", {"status": "reversed", "response": "Checked the camera"}, boss_tok)
check("a manager cannot reverse a point (HR only)", s == 403, f"{s}")
s, r = call("PUT", f"/decisions/point/{PT}/respond", {"status": "reversed", "response": "Checked the camera, removed"}, hr)
check("HR reverses the point", s == 200, f"{s} {r}")
s, r = call("GET", "/decisions", None, emp_tok)
check("the voided point disappears from the list", not any(x["kind"] == "point" for x in r), f"{[x['kind'] for x in r]}")
s, r = call("POST", f"/decisions/request/{R1}/dispute", {"message": "I have a medical need for the spot"}, emp_tok)
s, r = call("PUT", f"/decisions/request/{R1}/respond", {"status": "upheld", "response": "Policy applies to everyone"}, hr)
check("HR upholds a request rejection", s == 200 and r["dispute"]["status"] == "upheld", f"{s} {r}")
s, r = call("GET", "/requests", None, emp_tok)
rows = r if isinstance(r, list) else r.get("items", r.get("data", []))
check("upholding leaves the request rejected", [x for x in rows if x["id"] == R1][0]["status"] == "rejected", f"{rows[:1]}")

print("== summary")
s, r = call("GET", "/decisions/summary", None, hr)
check("summary counts", s == 200 and r["reversed"] == 2 and r["upheld"] == 1 and r["open"] == 0 and r["answered"] == 3, f"{r}")
s, r = call("GET", "/decisions/summary", None, emp_tok)
check("summary is HR only", s == 403, f"{s}")

print("== switching off closes everything, data stays")
switch(C, fair_decisions=False)
s, r = call("GET", "/decisions", None, emp_tok)
check("closed again", s == 403 and r.get("code") == "feature_disabled", f"{s}")
s, r = call("POST", f"/decisions/leave/{L0}/dispute", {"message": "this was unfair to me"}, emp_tok)
check("cannot dispute while off", s == 403, f"{s}")
L2 = new_leave(emp_tok, (today + datetime.timedelta(days=50)).isoformat(), (today + datetime.timedelta(days=51)).isoformat())
s, r = call("PUT", f"/leaves/{L2}", {"status": "rejected"}, hr)
check("reason no longer required while off", s == 200, f"{s}")
switch(C, fair_decisions=True)
s, r = call("GET", "/decisions", None, hr)
check("switch on again: history intact", s == 200 and any(x["dispute"] for x in r), f"{len(r)}")

finish()
