"""Two-step approvals (head then HR) and complaints (head -> HR -> owner).
Run:  python api_test23_chain_complaints.py http://127.0.0.1:8098
"""
import datetime
from feat_common import *

print("== setup")
hr, hr_uid, C = company("chain")
boss_tok, BOSS, boss_uid = employee(hr, "boss", salary=15000)
a_tok, A, _ = employee(hr, "memberA", salary=8000, manager_id=BOSS)
b_tok, B, _ = employee(hr, "memberB", salary=8000, manager_id=BOSS)
x_tok, X, _ = employee(hr, "outsider", salary=8000)
today = datetime.date.today()


def day(n):
    return (today + datetime.timedelta(days=n)).isoformat()


def new_leave(tok, n):
    d = today + datetime.timedelta(days=n)
    d += datetime.timedelta(days=(7 - d.weekday()) % 7)          # a Monday, so both days are working days
    s, r = call("POST", "/leaves", {"type": "annual", "start_date": d.isoformat(), "end_date": (d + datetime.timedelta(days=1)).isoformat(), "reason": "family"}, tok)
    assert s == 201, (s, r)
    return r


print("== chain OFF: behaves as before (HR decides at once, no head step)")
l0 = new_leave(a_tok, 40)
check("no head status while the switch is off", l0.get("headStatus") in (None, ""), l0)
s, r = call("PUT", f"/leaves/{l0['id']}", {"status": "approved"}, hr)
check("HR approves directly when off", s == 200 and r["status"] == "approved", f"{s} {r}")

print("== switch ON")
switch(C, approval_chain=True)
l1 = new_leave(a_tok, 50)
check("new leave waits for the head", l1.get("headStatus") == "pending", l1)
s, r = call("PUT", f"/leaves/{l1['id']}", {"status": "approved"}, hr)
check("HR cannot decide before the head (409)", s == 409, f"{s} {r}")
s, r = call("PUT", f"/leaves/{l1['id']}", {"status": "approved"}, x_tok)
check("an outsider cannot decide", s == 403, f"{s} {r}")
s, r = call("PUT", f"/leaves/{l1['id']}", {"status": "approved", "skip_head": True}, hr)
check("HR skipping the head needs a written reason", s == 422, f"{s} {r}")
s, r = call("GET", "/notifications", None, hr)
nots = r if isinstance(r, list) else r.get("data", r.get("items", []))
check("HR was NOT told yet about the pending leave", not any(n.get("type") == "leave_request" and (n.get("data") or {}).get("leaveId") == l1["id"] for n in nots), nots[:3])

s, r = call("PUT", f"/leaves/{l1['id']}", {"status": "approved", "review_note": "ok from me"}, boss_tok)
check("head approves: still pending for HR", s == 200 and r["status"] == "pending" and r["headStatus"] == "approved", f"{s} {r}")
s, r = call("PUT", f"/leaves/{l1['id']}", {"status": "approved"}, boss_tok)
check("head cannot finish it alone", s == 409, f"{s} {r}")
s, r = call("GET", "/notifications", None, hr)
nots = r if isinstance(r, list) else r.get("data", r.get("items", []))
check("HR is told after the head approved", any(n.get("type") == "chain_head_approved" for n in nots), nots[:3])
s, r = call("PUT", f"/leaves/{l1['id']}", {"status": "approved"}, hr)
check("HR gives the final approval", s == 200 and r["status"] == "approved", f"{s} {r}")

print("== head rejects")
l2 = new_leave(a_tok, 60)
s, r = call("PUT", f"/leaves/{l2['id']}", {"status": "rejected", "review_note": "busy week"}, boss_tok)
check("head rejection is final", s == 200 and r["status"] == "rejected" and r["headStatus"] == "rejected", f"{s} {r}")

print("== HR skips an absent head with a reason")
l3 = new_leave(b_tok, 70)
s, r = call("PUT", f"/leaves/{l3['id']}", {"status": "approved", "skip_head": True, "review_note": "head on long leave"}, hr)
check("skip recorded", s == 200 and r["status"] == "approved" and r["headStatus"] == "skipped", f"{s} {r}")

print("== employee without a head goes straight to HR")
l4 = new_leave(x_tok, 80)
check("no head -> no head step", l4.get("headStatus") in (None, ""), l4)

print("== general requests")
s, r = call("POST", "/requests", {"type": "equipment", "title": "New chair", "description": "back pain"}, a_tok)
R1 = r["id"]
check("equipment request waits for the head", s == 201 and r.get("headStatus") == "pending", f"{s} {r}")
s, r = call("PUT", f"/requests/{R1}", {"status": "approved"}, hr)
check("HR blocked on request until head", s == 409, f"{s} {r}")
s, r = call("PUT", f"/requests/{R1}", {"status": "approved"}, boss_tok)
check("head approves request", s == 200 and r["status"] == "pending" and r["headStatus"] == "approved", f"{s} {r}")
s, r = call("PUT", f"/requests/{R1}", {"status": "approved"}, hr)
check("HR final on request", s == 200 and r["status"] == "approved", f"{s} {r}")

print("== switch OFF in the middle: pending head step no longer blocks")
l5 = new_leave(a_tok, 90)
switch(C, approval_chain=False)
s, r = call("PUT", f"/leaves/{l5['id']}", {"status": "approved"}, hr)
check("back to one step when off", s == 200 and r["status"] == "approved", f"{s} {r}")

print("== complaints: closed while off")
s, r = call("GET", "/complaints", None, boss_tok)
check("complaints closed while off", s == 403 and r.get("code") == "feature_disabled", f"{s} {r}")
switch(C, complaints=True)

print("== filing")
s, r = call("POST", "/complaints", {"kind": "member", "target_employee_id": A, "subject": "Late again", "body": "Third time this week"}, x_tok)
check("a non-head cannot file", s == 403, f"{s} {r}")
s, r = call("POST", "/complaints", {"kind": "member", "target_employee_id": X, "subject": "Not mine", "body": "Not in my team at all"}, boss_tok)
check("cannot complain about someone outside the team", s == 422, f"{s} {r}")
s, r = call("POST", "/complaints", {"kind": "member", "target_employee_id": A, "subject": "Late again", "body": "short"}, boss_tok)
check("too-short text refused", s == 422, f"{s} {r}")
s, r = call("POST", "/complaints", {"kind": "member", "target_employee_id": A, "subject": "Late again", "body": "Third time this week without a call", "severity": "high"}, boss_tok)
K1 = r.get("id")
check("head files a complaint about a member", s == 201 and K1 and r["severity"] == "high", f"{s} {r}")
s, r = call("POST", "/complaints", {"kind": "hr", "subject": "Need a second laptop for the team", "body": "Support has been slow for two weeks on this"}, boss_tok)
K2 = r.get("id")
check("head files a complaint to HR", s == 201 and K2, f"{s} {r}")

print("== who sees what")
s, r = call("GET", "/complaints/team", None, boss_tok)
check("head sees the team (2 people)", s == 200 and len(r) == 2, f"{s} {r}")
s, r = call("GET", "/complaints", None, boss_tok)
check("head sees only own complaints", s == 200 and {c["id"] for c in r} == {K1, K2}, f"{s} {r}")
s, r = call("GET", "/complaints", None, hr)
check("HR sees all", s == 200 and {K1, K2} <= {c["id"] for c in r}, f"{s} {r}")
s, r = call("GET", "/complaints", None, a_tok)
check("the person complained about gets no list", s == 403, f"{s} {r}")
s, r = call("GET", f"/complaints/{K1}", None, a_tok)
check("...and cannot open it (404)", s == 404, f"{s} {r}")
s, r = call("GET", f"/complaints/{K1}", None, x_tok)
check("outsider cannot open it", s == 404, f"{s} {r}")
s, r = call("GET", "/complaints/owner", None, hr)
check("company admin is not the owner", s == 403, f"{s} {r}")

print("== HR answers")
s, r = call("PUT", f"/complaints/{K1}", {"action": "respond", "status": "in_review"}, boss_tok)
check("head cannot answer his own complaint", s == 403, f"{s} {r}")
s, r = call("PUT", f"/complaints/{K1}", {"action": "respond", "status": "resolved"}, hr)
check("resolving needs a note", s == 422, f"{s} {r}")
s, r = call("PUT", f"/complaints/{K2}", {"action": "respond", "status": "resolved", "note": "Laptop ordered, arrives Sunday"}, hr)
check("HR resolves the complaint to HR", s == 200 and r["status"] == "resolved", f"{s} {r}")
check("thread has filed + resolved", [e["action"] for e in r["events"]] == ["filed", "resolved"], r.get("events"))
s, r = call("PUT", f"/complaints/{K2}", {"action": "comment", "note": "thanks"}, boss_tok)
check("head cannot write on a closed complaint", s == 409, f"{s} {r}")
s, r = call("GET", "/notifications", None, boss_tok)
nots = r if isinstance(r, list) else r.get("data", r.get("items", []))
check("head was told about the outcome", any(n.get("type") == "complaint" for n in nots), nots[:3])

print("== HR sends it up to the owner")
s, r = call("PUT", f"/complaints/{K1}", {"action": "escalate"}, hr)
check("escalation needs a reason", s == 422, f"{s} {r}")
s, r = call("PUT", f"/complaints/{K1}", {"action": "escalate", "note": "Repeated problem, you should see it"}, boss_tok)
check("head cannot escalate", s == 403, f"{s} {r}")
s, r = call("PUT", f"/complaints/{K1}", {"action": "escalate", "note": "Repeated problem, you should see it"}, hr)
check("HR escalates", s == 200 and r["status"] == "escalated", f"{s} {r}")
s, r = call("PUT", f"/complaints/{K1}", {"action": "escalate", "note": "again please"}, hr)
check("only once", s == 409, f"{s} {r}")

otok = owner_token()
oc = owner_company()
switch(oc, complaints=True)
s, r = call("GET", "/complaints/owner", None, otok)
check("platform owner sees the escalated one", s == 200 and any(c["id"] == K1 for c in r), f"{s} {r}")
check("...but not the one that stayed with HR", not any(c["id"] == K2 for c in r), r)
s, r = call("GET", f"/complaints/{K1}", None, otok)
check("owner opens it", s == 200 and r["myRole"] == "owner" and len(r["events"]) >= 2, f"{s} {r}")
s, r = call("GET", f"/complaints/{K2}", None, otok)
check("owner cannot open one that was not sent up (404)", s == 404, f"{s} {r}")
s, r = call("PUT", f"/complaints/{K1}", {"action": "comment", "note": "I will talk to him on Monday"}, otok)
check("owner comments", s == 200 and r["events"][-1]["actorRole"] == "owner", f"{s} {r}")
s, r = call("GET", f"/complaints/{K1}", None, hr)
check("HR sees the owner's note", s == 200 and any(e["actorRole"] == "owner" for e in r["events"]), f"{s} {r}")
s, r = call("GET", f"/complaints/{K1}", None, boss_tok)
check("head sees the owner's note too", s == 200 and any(e["actorRole"] == "owner" for e in r["events"]), f"{s} {r}")
s, r = call("PUT", f"/complaints/{K1}", {"action": "respond", "status": "resolved", "note": "Spoke with him, warned in writing"}, otok)
check("owner closes it", s == 200 and r["status"] == "resolved", f"{s} {r}")

print("== switching complaints OFF closes it for HR and heads")
switch(C, complaints=False)
s, r = call("GET", "/complaints", None, hr)
check("closed for HR", s == 403 and r.get("code") == "feature_disabled", f"{s} {r}")
s, r = call("POST", "/complaints", {"kind": "hr", "subject": "x", "body": "something long enough"}, boss_tok)
check("closed for heads", s == 403, f"{s} {r}")

finish()
